#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn settings_section_headings_en_fr() {
        for lang in ["en", "fr"] {
            let t = strings(lang);
            assert!(!t.settings_me.is_empty());
            assert!(!t.settings_models.is_empty());
            assert!(!t.settings_trust.is_empty());
        }
    }

    #[test]
    fn routing_human_labels_avoid_raw_codes() {
        let t = strings("en");
        assert!(!routing_label(&t, "local_only").contains("local_only"));
        assert!(!routing_label(&t, "balanced").starts_with("balanced ("));
        assert!(!routing_label(&t, "remote_only").contains("remote_only"));
        assert!(routing_technical(&t, "local_only").contains("local_only"));
    }

    #[test]
    fn roster_tool_labels_avoid_raw_ids() {
        let t = strings("en");
        assert_eq!(roster_tool_label(&t, "notes.create"), "Create note");
        assert!(!roster_tool_label(&t, "notes.create").contains('.'));
        let t_fr = strings("fr");
        assert_eq!(roster_tool_label(&t_fr, "notes.create"), "Créer une note");
        assert_eq!(t_fr.agents_skills, "Compétences");
    }

    #[test]
    fn agent_could_not_act_i18n_keys() {
        let en = strings("en");
        let fr = strings("fr");
        assert_eq!(en.agent_could_not_act, "The agent could not act.");
        assert_eq!(fr.agent_could_not_act, "L'agent n'a pas pu agir.");
        assert_ne!(en.agent_could_not_act, fr.agent_could_not_act);
        let resolved = resolve_agent_fail_reason(
            &en,
            Some(aos_agent::actions::THREAD_FAIL_COULD_NOT_ACT),
        );
        assert_eq!(resolved, en.agent_could_not_act);
        assert!(!resolved.contains("JSON"));
        assert!(!resolved.contains("notes.create"));
    }

    #[test]
    fn agent_act_phrase_keys_en_fr() {
        for lang in ["en", "fr"] {
            let t = strings(lang);
            assert!(!t.agent_act_notes_create.is_empty());
            assert!(!t.agent_act_canvas_stroke.is_empty());
            assert!(t.agent_act_notes_create_title.contains("{title}"));
        }
        let en = strings("en");
        let fr = strings("fr");
        assert_ne!(en.agent_act_canvas_stroke, fr.agent_act_canvas_stroke);
    }
}
